// Config holds GitAI configuration
type Config struct {
	Model        string           `toml:"model"`
	ExchangeRate float64          `toml:"exchange_rate"`
	Currency     string           `toml:"default_currency"`
	Models       map[string]Model `toml:"models"`
	UserSettings map[string]string `toml:"user"`
}

// Model represents a custom model configuration
